	}

	/** Коды всех ролей модуля. @return list<string> */
	public static function codes(): array
	{
		return array_map(static fn(array $raw): string => $raw['code'], static::raw());
	}

	/**
	 * @param list<string> $examples
	 * @param list<string> $lines
	 */
	private static function role(string $code, string $title, int $sort, string $description, array $examples, array $lines): array
	{
		return [
			'code' => $code,
			'kind' => 'role',
			'title' => $title,
			'description' => $description,
			'sort' => $sort,
			'examples' => $examples,
			'text' => implode("\n", array_merge($lines, [''], self::RULES)),
		];
	}
